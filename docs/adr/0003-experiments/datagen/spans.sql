-- One app, one day of synthetic RUM spans: per session 15 `view` spans and 40 fetch spans.
-- Params: day (0 = the 24 h ending now), app (0..2), sessions (per app and day).
INSERT INTO signoz_traces.signoz_index_v3
(
    ts_bucket_start, resource_fingerprint, timestamp, trace_id, span_id, trace_state, parent_span_id, flags,
    name, kind, kind_string, duration_nano, status_code, status_message, status_code_string,
    attributes_string, attributes_number, attributes_bool, resources_string, events, links,
    response_status_code, external_http_url, http_url, external_http_method, http_method, http_host,
    db_name, db_operation, has_error, is_remote, inserted_at
)
WITH
    {app:UInt8} AS a,
    {day:UInt8} AS d,
    ['shop-web', 'backoffice-web', 'docs-web'][a + 1] AS app,
    ['/', '/products/:id', '/category/:id', '/search', '/cart', '/checkout', '/orders', '/orders/:id', '/account', '/help', '/blog/:id', '/wishlist'] AS routes,
    toUnixTimestamp(now()) - 3600 - (d + 1) * 86400 AS day_start,
    intDiv(number, 55) AS s,
    number % 55 AS k,
    cityHash64('rum0', a, d, s) AS h,
    lower(hex(MD5(concat('rum0-', toString(a), '-', toString(d), '-', toString(s))))) AS session_id,
    bitShiftRight(h, 8) % 150 AS ua_idx,
    ['Windows', 'macOS', 'Linux', 'Android', 'iOS'][ua_idx % 5 + 1] AS platform,
    if(platform IN ('Android', 'iOS'), 'true', 'false') AS mobile,
    multiIf(bitShiftRight(h, 16) % 10 < 6, '2.4.1', bitShiftRight(h, 16) % 10 < 9, '2.4.0', '2.3.7') AS version,
    concat('Mozilla/5.0 (', platform, ') AppleWebKit/537.36 (KHTML, like Gecko) Chrome/', toString(120 + ua_idx % 30), '.0.', toString(6000 + ua_idx), '.0 Safari/537.36') AS ua,
    map('service.name', app, 'service.version', version, 'deployment.environment.name', 'production',
        'fusescope.rum.platform', 'web', 'fusescope.spike', 'rum0', 'telemetry.distro.name', '@fusescope/browser',
        'telemetry.sdk.language', 'webjs', 'user_agent.original', ua, 'browser.platform', platform,
        'browser.mobile', mobile, 'browser.language', 'en-US') AS res,
    concat('service.name=', app, ';hash=', toString(cityHash64(toJSONString(res)))) AS fingerprint,
    30 + h % 90 AS view_gap_s,
    toInt64(day_start + h % 86400) * 1000 AS session_start_ms,
    k < 15 AS is_view,
    if(is_view, k, intDiv((k - 15) * 15, 40)) AS view_idx,
    routes[(h + view_idx * 7) % length(routes) + 1] AS route,
    cityHash64(h, k) AS hk,
    session_start_ms + view_idx * view_gap_s * 1000 + if(is_view, 0, 200 + ((k - 15) % 3) * 1500 + hk % 1000) AS ts_ms,
    if(is_view, toUInt64(view_gap_s) * 1000000000, (50 + hk % 750) * 1000000) AS dur,
    hk % 100 < 3 AS failed,
    if(hk % 4 = 0, 'POST', 'GET') AS method,
    concat('https://api.', app, '.example.com/v1/', ['products', 'cart', 'orders', 'search', 'session', 'recommendations'][hk % 6 + 1]) AS url
SELECT
    intDiv(intDiv(ts_ms, 1000), 1800) * 1800,
    fingerprint,
    fromUnixTimestamp64Milli(ts_ms),
    lower(hex(MD5(concat(session_id, toString(if(is_view, k, 1000 + k)))))),
    substring(lower(hex(MD5(concat(session_id, 's', toString(k))))), 1, 16),
    '',
    '',
    257,
    if(is_view, 'view', method),
    if(is_view, 1, 3),
    if(is_view, 'Internal', 'Client'),
    dur,
    if(failed, 2, 0),
    '',
    if(failed, 'Error', 'Unset'),
    if(is_view,
       map('session.id', session_id, 'fusescope.rum.view.route', route, 'url.path', replaceOne(route, ':id', toString(hk % 1000)),
           'fusescope.rum.view.navigation_type', if(k = 0, 'load', 'push')),
       map('session.id', session_id, 'fusescope.rum.view.route', route, 'url.full', url, 'http.request.method', method,
           'server.address', concat('api.', app, '.example.com'))),
    if(is_view, map(), map('http.response.status_code', if(failed, 500., 200.))),
    map(),
    res,
    [],
    '[]',
    if(is_view, '', if(failed, '500', '200')),
    if(is_view, '', url),
    if(is_view, '', url),
    if(is_view, '', method),
    if(is_view, '', method),
    if(is_view, '', concat('api.', app, '.example.com')),
    '',
    '',
    failed,
    'no',
    now64(3)
FROM numbers({sessions:UInt32} * 55)
SETTINGS max_block_size = 65536, max_insert_block_size = 1048576, max_threads = 4;
