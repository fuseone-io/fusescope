-- One day of signoz_index_v3: n spans, 10 per trace. Params as gen-logs.sql.
INSERT INTO signoz_traces.signoz_index_v3 (ts_bucket_start, resource_fingerprint, timestamp, trace_id, span_id, parent_span_id, flags,
  name, kind, kind_string, duration_nano, status_code, status_message, status_code_string, attributes_string, attributes_number,
  attributes_bool, resources_string, events, links, response_status_code, http_url, http_method, http_host, db_name, db_operation,
  has_error, is_remote, inserted_at)
WITH
  {t0:UInt32} - ({days:UInt32} - {day:UInt32}) * 86400 AS day_start,
  intDiv(number, 10) AS tn,
  number % 10 AS idx,
  {day:UInt32} * 150000 + tn AS trace_n,
  sipHash64(number, {day:UInt32}) AS r,
  day_start + intDiv(tn * 86400, intDiv({n:UInt32}, 10)) AS ts_s,
  toDateTime64(ts_s, 9) + toIntervalNanosecond(idx * 3000000 + r % 1000000) AS ts,
  (trace_n + idx * 7) % 30 AS svc,
  (svc * 8 + (trace_n % 8)) AS res,
  ['/api/v1/orders', '/api/v1/orders/{id}', '/api/v1/cart', '/api/v1/checkout', '/api/v1/users/{id}', '/api/v1/search',
   '/api/v1/payments', '/healthz', '/api/v1/inventory', '/api/v1/shipping'][1 + ((trace_n + idx) % 10)] AS route,
  ['GET', 'GET', 'GET', 'POST', 'PUT', 'DELETE'][1 + (r % 6)] AS method,
  (r % 100) < 3 AS err,
  multiIf(err, 500, r % 20 = 0, 404, 200) AS http_status,
  idx >= 7 AS is_db
SELECT
  intDiv(ts_s, 1800) * 1800,
  toString(cityHash64(res)),
  ts,
  lower(hex(MD5(toString(trace_n)))),
  lower(hex(substring(MD5(concat(toString(trace_n), '-', toString(idx))), 1, 8))),
  if(idx = 0, '', lower(hex(substring(MD5(concat(toString(trace_n), '-', toString(intDiv(idx - 1, 3) * 3))), 1, 8)))),
  1,
  if(is_db, concat('SELECT ', ['orders', 'users', 'carts'][1 + (r % 3)]), concat(method, ' ', route)),
  if(idx = 0, 2, if(is_db, 3, 2 + (idx % 2))),
  if(idx = 0, 'Server', if(is_db, 'Client', ['Server', 'Client'][1 + (idx % 2)])),
  toUInt64(exp((r % 1000) / 150.0) * 1000000) * if(idx = 0, 3, 1),
  if(err, 2, 0),
  if(err, ['upstream timeout', 'connection reset', 'null pointer'][1 + (r % 3)], ''),
  if(err, 'Error', 'Unset'),
  if(is_db, map('db.system', 'postgresql', 'db.name', 'shop', 'db.statement', 'SELECT * FROM orders WHERE id = $1'),
            map('http.method', method, 'http.route', route, 'user.id', toString(r % 500000))),
  map('http.status_code', toFloat64(http_status)),
  map('retry', r % 30 = 0),
  map('service.name', concat('svc-', leftPad(toString(svc), 2, '0')), 'k8s.pod.name', concat('svc-', leftPad(toString(svc), 2, '0'), '-', lower(hex(cityHash64(res) % 65536))),
      'k8s.namespace.name', ['shop', 'payments', 'platform'][1 + (svc % 3)], 'host.name', concat('node-', toString(res % 12)), 'deployment.environment', 'prod'),
  if(err, [concat('{"name":"exception","timeUnixNano":', toString(toUnixTimestamp64Nano(ts)), ',"attributeMap":{"exception.type":"TimeoutError","exception.message":"upstream timeout"}}')], []),
  '[]',
  if(is_db, '', toString(http_status)),
  if(is_db, '', concat('http://svc-', leftPad(toString(svc), 2, '0'), route)),
  if(is_db, '', method),
  if(is_db, '', concat('svc-', leftPad(toString(svc), 2, '0'))),
  if(is_db, 'shop', ''),
  if(is_db, 'SELECT', ''),
  err,
  if(idx = 0, 'no', 'yes'),
  toDateTime64(ts_s, 3)
FROM numbers({n:UInt32})
SETTINGS max_insert_threads = 2, max_threads = 4, max_block_size = 65536, min_insert_block_size_rows = 262144, min_insert_block_size_bytes = 268435456, max_memory_usage = 6000000000;
